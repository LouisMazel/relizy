import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { multiselect } from '@clack/prompts'
import { AGENT_TARGETS } from '@maz-ui/node'
import { addAgentRulesCommand, askAgentTargets, findOutdatedRules, getDefaultAgentTargets, readOwnAgentDocs, RELIZY_AGENTS_TOOL, setupPrepareScript, setupRelizyAgents } from '../agents'
import { cleanTempDirs, createTempDir, getBundleDir, writeOutdatedRules } from '../mcp/__tests__/helpers'
import { readOwnVersion } from '../own-version'

vi.mock('@clack/prompts', () => ({
  multiselect: vi.fn(),
}))

let cwd: string

beforeEach(() => {
  cwd = createTempDir()
})

afterAll(() => {
  cleanTempDirs()
})

function read(file: string): string {
  return readFileSync(join(cwd, file), 'utf8')
}

describe('Given askAgentTargets', () => {
  describe('When the project already uses agents', () => {
    it('Then they are checked, and AGENTS.md is added to an agent other than Claude Code', async () => {
      writeFileSync(join(cwd, 'CLAUDE.md'), '# project')
      vi.mocked(multiselect).mockResolvedValueOnce(['cursor'])

      expect(await askAgentTargets(cwd)).toEqual(['agents-md', 'cursor'])
      expect(vi.mocked(multiselect)).toHaveBeenCalledWith(expect.objectContaining({
        message: 'Which AI agents do you use?',
        initialValues: ['claude'],
        required: true,
      }))
    })
  })

  describe('When only Claude Code is chosen', () => {
    it('Then AGENTS.md is not added', async () => {
      vi.mocked(multiselect).mockResolvedValueOnce(['claude'])

      expect(await askAgentTargets(cwd)).toEqual(['claude'])
    })
  })

  describe('When the question is cancelled', () => {
    it('Then it returns the cancel symbol', async () => {
      const cancelled = Symbol('cancel')
      vi.mocked(multiselect).mockResolvedValueOnce(cancelled as never)

      expect(await askAgentTargets(cwd)).toBe(cancelled)
    })
  })
})

describe('Given setupRelizyAgents', () => {
  describe('When the project uses Claude Code', () => {
    it('Then it writes the relizy rule and registers relizy mcp', () => {
      writeFileSync(join(cwd, 'CLAUDE.md'), '# project')

      const result = setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })

      expect(result.targets).toEqual(['claude'])
      expect(read('.claude/rules/relizy.md')).toContain(`<!-- Managed by relizy ${readOwnVersion()}`)
      expect(read('.claude/rules/relizy.md')).toContain('generated by `relizy mcp init`')
      expect(read('.claude/rules/relizy.md')).toContain('> These rules and the docs in `node_modules/relizy/agent-docs` match the installed relizy.')
      expect(JSON.parse(read('.mcp.json'))).toEqual({
        mcpServers: {
          relizy: {
            type: 'stdio',
            command: 'npx',
            args: ['-y', `relizy@${readOwnVersion()}`, 'mcp'],
          },
        },
      })
    })
  })

  describe('When the project installs relizy with pnpm', () => {
    it('Then the agents start the installed relizy', () => {
      writeFileSync(join(cwd, 'package.json'), JSON.stringify({
        packageManager: 'pnpm@10.0.0',
        devDependencies: { relizy: '^1.0.0' },
      }))

      const result = setupRelizyAgents({
        cwd,
        targets: ['cursor'],
        docsDir: getBundleDir(),
      })

      expect(result.localMcpServer).toBe(true)
      expect(JSON.parse(read('.cursor/mcp.json'))).toEqual({
        mcpServers: {
          relizy: {
            command: 'pnpm',
            args: ['exec', 'relizy', 'mcp'],
          },
        },
      })
    })
  })

  describe('When the targets are an agent other than Claude Code', () => {
    it('Then AGENTS.md is added for its rules, unless only the MCP server is registered', () => {
      const mcpOnly = setupRelizyAgents({
        cwd,
        targets: ['cursor'],
        rules: false,
        dryRun: true,
      })
      const result = setupRelizyAgents({
        cwd,
        targets: ['cursor'],
        docsDir: getBundleDir(),
      })

      expect(mcpOnly.targets).toEqual(['cursor'])
      expect(result.targets).toEqual(['agents-md', 'cursor'])
      expect(read('AGENTS.md')).toContain('<!-- BEGIN:relizy -->')
    })
  })

  describe('When the project has no agent', () => {
    it('Then Claude Code and AGENTS.md are configured', () => {
      expect(getDefaultAgentTargets(cwd)).toEqual(['claude', 'agents-md'])

      setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })

      expect(read('AGENTS.md')).toContain('<!-- BEGIN:relizy -->')
      expect(read('AGENTS.md')).toContain('## relizy')
    })
  })

  describe('When the targets are invalid', () => {
    it('Then it lists the available ones', () => {
      expect(() => setupRelizyAgents({
        cwd,
        targets: ['claude', 'zed' as never],
      })).toThrow(`Unknown agent target(s): zed. Available: ${AGENT_TARGETS.join(', ')}.`)
    })
  })

  describe('When the setup is removed', () => {
    it('Then the files of relizy are removed', () => {
      setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })
      setupRelizyAgents({ cwd, remove: true })

      expect(existsSync(join(cwd, 'AGENTS.md'))).toBe(false)
      expect(existsSync(join(cwd, '.mcp.json'))).toBe(false)
    })
  })
})

describe('Given readOwnAgentDocs', () => {
  describe('When the bundle has no rules', () => {
    it('Then it explains how to get them', () => {
      expect(() => readOwnAgentDocs(createTempDir())).toThrow('The rules of relizy for the agents are missing')
    })
  })

  describe('When the bundle has the rules', () => {
    it('Then they are read with the version of relizy', () => {
      expect(readOwnAgentDocs(getBundleDir())).toEqual(expect.objectContaining({
        version: readOwnVersion(),
        claudeRule: expect.stringMatching(/^# relizy/),
      }))
    })
  })
})

describe('Given findOutdatedRules', () => {
  describe('When the rules of the project changed', () => {
    it('Then the rule files to update are reported, without writing', () => {
      writeOutdatedRules(cwd)
      const before = read('.claude/rules/relizy.md')

      expect(findOutdatedRules(cwd)).toEqual(['.claude/rules/relizy.md'])
      expect(read('.claude/rules/relizy.md')).toBe(before)
      expect(existsSync(join(cwd, 'AGENTS.md'))).toBe(false)
      expect(existsSync(join(cwd, '.mcp.json'))).toBe(false)
    })
  })

  describe('When the rules are missing or up to date', () => {
    it('Then nothing is reported', () => {
      expect(findOutdatedRules(cwd)).toEqual([])

      setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })

      expect(findOutdatedRules(cwd)).toEqual([])
    })
  })

  describe('When AGENTS.md has no section of relizy', () => {
    it('Then it is not reported', () => {
      writeFileSync(join(cwd, 'AGENTS.md'), '# Agents\n\nRules of the project.\n')

      expect(findOutdatedRules(cwd)).toEqual([])
    })
  })

  describe('When the rules cannot be read', () => {
    it('Then nothing is reported', () => {
      expect(findOutdatedRules(join(cwd, 'missing', 'folder'))).toEqual([])
    })
  })
})

describe('Given the note of the rules', () => {
  describe('When it is built', () => {
    it('Then it does not contain the version, so a release alone does not change the rules', () => {
      const note = (RELIZY_AGENTS_TOOL.versionNote as (version: string) => string)('9.9.9')

      expect(note).not.toContain('9.9.9')
      expect(note).toContain('match the installed relizy')
    })
  })
})

describe('Given addAgentRulesCommand', () => {
  describe('When the prepare script is missing, another command or already set up', () => {
    it('Then it creates it, appends to it, or keeps it', () => {
      expect(addAgentRulesCommand(undefined)).toBe('relizy mcp update')
      expect(addAgentRulesCommand('husky')).toBe('husky && relizy mcp update')
      expect(addAgentRulesCommand('husky && relizy mcp update')).toBeUndefined()
      expect(addAgentRulesCommand('relizy mcp init')).toBeUndefined()
    })
  })
})

describe('Given setupPrepareScript', () => {
  describe('When the root package.json has no prepare script', () => {
    it('Then it adds it, keeping the indentation, and is up to date the second time', () => {
      writeFileSync(join(cwd, 'package.json'), '{\n    "name": "lib"\n}\n')

      expect(setupPrepareScript({ cwd })).toEqual({ file: 'package.json', action: 'update', reason: 'prepare script: relizy mcp update' })
      expect(read('package.json')).toBe('{\n    "name": "lib",\n    "scripts": {\n        "prepare": "relizy mcp update"\n    }\n}\n')
      expect(setupPrepareScript({ cwd })).toEqual({ file: 'package.json', action: 'unchanged', reason: 'prepare script' })
    })
  })

  describe('When it removes the command', () => {
    it('Then it keeps the other commands, and drops the script and the empty scripts', () => {
      writeFileSync(join(cwd, 'package.json'), JSON.stringify({
        name: 'lib',
        scripts: { prepare: 'husky && relizy mcp update', build: 'tsc' },
      }))
      expect(setupPrepareScript({ cwd, remove: true })?.action).toBe('update')
      expect(JSON.parse(read('package.json')).scripts).toEqual({ prepare: 'husky', build: 'tsc' })
      expect(setupPrepareScript({ cwd, remove: true })).toBeUndefined()

      writeFileSync(join(cwd, 'package.json'), JSON.stringify({
        name: 'lib',
        scripts: { prepare: 'relizy mcp update' },
      }))
      setupPrepareScript({ cwd, remove: true })
      expect(JSON.parse(read('package.json'))).toEqual({ name: 'lib' })
    })
  })

  describe('When it runs in dry run, without package.json or with an invalid one', () => {
    it('Then it writes nothing', () => {
      expect(setupPrepareScript({ cwd })).toBeUndefined()

      writeFileSync(join(cwd, 'package.json'), '{ "name": "lib" }')
      expect(setupPrepareScript({ cwd, dryRun: true })?.action).toBe('update')
      expect(read('package.json')).toBe('{ "name": "lib" }')

      writeFileSync(join(cwd, 'package.json'), '{ invalid')
      expect(setupPrepareScript({ cwd })?.action).toBe('skip')
      expect(read('package.json')).toBe('{ invalid')
    })
  })
})

describe('Given RELIZY_AGENTS_TOOL', () => {
  describe('When it is read', () => {
    it('Then the agents run relizy mcp', () => {
      expect(RELIZY_AGENTS_TOOL).toEqual(expect.objectContaining({
        name: 'relizy',
        mcpPackage: 'relizy',
        mcpBin: 'relizy',
        mcpArgs: ['mcp'],
      }))
    })
  })
})
