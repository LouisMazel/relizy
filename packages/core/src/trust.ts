/**
 * npm trusted publishers: which CI workflow may publish or stage a package
 * with OIDC (`npm trust`, npm 11.15.0+, with the npm login and 2FA of a
 * maintainer, on a package that exists). See https://docs.npmjs.com/trusted-publishers
 */

type Env = NodeJS.ProcessEnv

/** Who a trusted publisher configuration trusts */
export type TrustedPublisherSource
  = | { type: 'github', file: string, repository: string, environment?: string }
    | { type: 'gitlab', file: string, project: string, environment?: string }
    | { type: 'circleci', orgId: string, projectId: string, pipelineDefinitionId: string, vcsOrigin: string, contextIds?: string[] }

/** A trusted publisher configuration of a package, as `npm trust list` gives it */
export interface TrustedPublisher {
  /** Id of the configuration, for `revokeTrustedPublisher` */
  id?: string
  /** `github`, `gitlab`, `circleci`, or what npm gives */
  type: string
  /** Workflow or CI config file (GitHub, GitLab) */
  file?: string
  /** `owner/repo` (GitHub) or `group/project` (GitLab) */
  repository?: string
  environment?: string
  /** Direct publish allowed (`--allow-publish`) */
  allowPublish?: boolean
  /** Staged publish allowed (`--allow-stage-publish`) */
  allowStagePublish?: boolean
  /** The object npm printed */
  raw: Record<string, unknown>
}

/** The outcome of setting up the trusted publishing of one package */
export interface TrustResult {
  name: string
  /** `created`, `exists` (same configuration), `differs` (same workflow, other permissions or environment), `replaced`, `missing` (not on npm), `failed` */
  status: 'created' | 'exists' | 'differs' | 'replaced' | 'missing' | 'failed'
  reason?: string
  publishers?: TrustedPublisher[]
}

/** A CI workflow that releases with relizy, read from the files of the project */
export interface ReleaseWorkflow {
  provider: 'github' | 'gitlab'
  /** File name npm matches (`release.yml`, `.gitlab-ci.yml`) */
  file: string
  /** Path relative to the root of the project */
  path: string
  /** `owner/repo` or `group/project`, from the git remote or the `repository` of `package.json` */
  repository?: string
  /** Written by `relizy init` */
  generated: boolean
  /** The jobs that release, with their environment */
  jobs: { name: string, environment?: string }[]
}

/** The options of the `npm trust` calls */
export interface TrustCallOptions {
  /** Root of the project */
  cwd: string
  /** Package to set up */
  packageName: string
  /** The 2FA code */
  otp?: string
  /** Runs npm (the default one without a terminal) */
  runner?: NpmCommandRunner
  /** Environment to check for a CI or trusted publishing (`process.env` by default) */
  env?: Env
  /** Timeout of the npm call (60000 by default) */
  timeoutMs?: number
  logger?: CoreLogger
  /** Shows the web 2FA page of a security-key account, then the call goes on once validated */
  onWebAuth?: WebAuthHandler
}

const GENERATED_HEADER = '# Generated by relizy init'
const BLANKED_TOKENS = { NPM_TOKEN: '', NODE_AUTH_TOKEN: '', RELIZY_NPM_TOKEN: '' }

function getErrorText(error: unknown): string {
  if (typeof error !== 'object' || error === null) {
    return String(error)
  }
  const record = error as Record<string, unknown>
  return [record.message, record.stdout, record.stderr].filter(value => typeof value === 'string').join('\n')
}

async function runTrust(options: TrustCallOptions, args: string[]): Promise<string> {
  assertInteractiveNpmAuth(options.env)
  const runner = options.runner ?? runNpmCommand

  try {
    return await withWebAuth(async (otp) => {
      const { stdout } = await runner(otp
        // `--otp <code>` gives an unknown positional argument to `npm trust`
        ? [...args, `--otp=${otp}`]
        : args, {
        cwd: tmpdir(),
        env: BLANKED_TOKENS,
        timeoutMs: options.timeoutMs ?? 60_000,
      })
      return stdout
    }, { otp: options.otp, onWebAuth: options.onWebAuth, purpose: 'trust' })
  }
  catch (error) {
    const text = getErrorText(error)
    const status = Number(/\bE(\d{3})\b/.exec(text)?.[1]) || undefined
    if (/bypass|two-factor authentication is required|basic auth/i.test(text) && !/EOTP/.test(text)) {
      throw new TrustedPublisherError(`npm refused to set up trusted publishing for ${options.packageName}: log in with "npm login" (a token, even one bypassing 2FA, cannot set it up)`, { status, cause: error })
    }
    // The OTP and web 2FA errors are given as is: the caller asks for a code
    if (/EOTP|one-time password/i.test(text)) {
      throw error
    }
    throw new TrustedPublisherError(`npm trust failed for ${options.packageName}: ${text.split('\n').find(Boolean) ?? 'unknown error'}`, { status, cause: error })
  }
}

/**
 * The JSON values printed one after the other (`npm trust --json` prints one
 * object per configuration, not an array); an array is flattened
 *
 * @param stdout - Output of the command.
 * @returns The values, in order; text between them and invalid JSON are skipped.
 * @example
 * ```ts
 * parseJsonStream('{"id":"a"}\n{"id":"b"}') // [{ id: 'a' }, { id: 'b' }]
 * ```
 */
export function parseJsonStream(stdout: string): unknown[] {
  const values: unknown[] = []
  let index = 0

  while (index < stdout.length) {
    const start = stdout.slice(index).search(/[[{]/)
    if (start === -1) {
      break
    }
    const begin = index + start
    const end = findJsonEnd(stdout, begin)
    if (end === -1) {
      break
    }
    try {
      values.push(JSON.parse(stdout.slice(begin, end + 1)))
    }
    catch {
      // Not JSON: skipped
    }
    index = end + 1
  }

  return values.flatMap(value => Array.isArray(value)
    ? value
    : [value])
}

/** The index of the bracket closing the one at `begin`, strings skipped, `-1` when it never closes */
function findJsonEnd(text: string, begin: number): number {
  let depth = 0
  let inString = false

  for (let index = begin; index < text.length; index++) {
    const char = text[index]
    if (inString) {
      if (char === '\\') {
        index++
      }
      else if (char === '"') {
        inString = false
      }
      continue
    }
    if (char === '"') {
      inString = true
    }
    else if (char === '{' || char === '[') {
      depth++
    }
    else if (char === '}' || char === ']') {
      depth--
      if (depth === 0) {
        return index
      }
    }
  }

  return -1
}

function pickString(record: Record<string, unknown>, ...keys: string[]): string | undefined {
  for (const key of keys) {
    if (typeof record[key] === 'string' && record[key]) {
      return record[key] as string
    }
  }
  return undefined
}

function pickBoolean(record: Record<string, unknown>, ...keys: string[]): boolean | undefined {
  for (const key of keys) {
    if (typeof record[key] === 'boolean') {
      return record[key] as boolean
    }
  }
  return undefined
}

function toPublisher(record: Record<string, unknown>): TrustedPublisher {
  const permissions = Array.isArray(record.permissions)
    ? record.permissions.map(String)
    : undefined
  return {
    id: pickString(record, 'id'),
    type: (pickString(record, 'type', 'provider') ?? 'unknown').toLowerCase(),
    file: pickString(record, 'file', 'workflow', 'workflowFile', 'ciConfigPath', 'configPath'),
    repository: pickString(record, 'repository', 'repo', 'project', 'projectPath'),
    environment: pickString(record, 'environment', 'env'),
    // npm gives `permissions: ['createPackage', 'createStagedPackage']` (a direct publish allows staging too)
    allowPublish: pickBoolean(record, 'allowPublish', 'allow_publish') ?? permissions?.some(permission => /^(?:createPackage|publish)$/i.test(permission)),
    allowStagePublish: pickBoolean(record, 'allowStagePublish', 'allowStagedPublish', 'allow_stage_publish') ?? permissions?.some(permission => /^(?:createStagedPackage|stage-?publish|staged?)$/i.test(permission)),
    raw: record,
  }
}

/**
 * The trusted publisher configurations of a package (`npm trust list <pkg>
 * --json`, which asks for the 2FA), with the npm login of the person: token
 * variables blanked, npm run from a neutral directory
 *
 * @param options - Package, code and runner.
 * @param options.cwd - Root of the project.
 * @param options.packageName - Package.
 * @param options.otp - The 2FA code.
 * @param options.runner - Runs npm (an interactive one for npm's web 2FA).
 * @param options.env - Environment to check.
 * @param options.timeoutMs - Timeout of the npm call.
 * @param options.logger - Receives debug messages.
 * @returns The configurations, empty when there is none.
 * @throws `InteractiveAuthRequiredError` in a CI or under trusted publishing, the OTP error of npm when it needs a code, `TrustedPublisherError` otherwise.
 * @example
 * ```ts
 * const publishers = await listTrustedPublishers({ cwd: '/repo', packageName: '@scope/core', otp: '123456' })
 * // [{ id: '...', type: 'github', file: 'release.yml', repository: 'acme/repo', allowPublish: true, ... }]
 * ```
 */
export async function listTrustedPublishers(options: TrustCallOptions): Promise<TrustedPublisher[]> {
  const stdout = await runTrust(options, [
    'trust',
    'list',
    options.packageName,
    '--json',
  ])
  return parseJsonStream(stdout)
    .filter((value): value is Record<string, unknown> => typeof value === 'object' && value !== null && !('error' in value))
    .map(toPublisher)
}

/**
 * The arguments of `npm trust <github|gitlab|circleci> <pkg>` for a source
 *
 * @param options - Package, source, permissions.
 * @param options.packageName - Package.
 * @param options.source - The workflow trusted.
 * @param options.allowPublish - Allow a direct publish.
 * @param options.allowStagePublish - Allow a staged publish.
 * @param options.dryRun - Pass `--dry-run`.
 * @returns The arguments, without `npm`.
 * @example
 * ```ts
 * getTrustArgs({ packageName: 'pkg', source: { type: 'github', file: 'release.yml', repository: 'acme/repo' }, allowPublish: true, allowStagePublish: false })
 * // ['trust', 'github', 'pkg', '--file', 'release.yml', '--repo', 'acme/repo', '--allow-publish', '--yes', '--json']
 * ```
 */
export function getTrustArgs({ packageName, source, allowPublish, allowStagePublish, dryRun = false }: {
  packageName: string
  source: TrustedPublisherSource
  allowPublish: boolean
  allowStagePublish: boolean
  dryRun?: boolean
}): string[] {
  if (!allowPublish && !allowStagePublish) {
    throw new TrustedPublisherError(`A trusted publisher of ${packageName} needs at least one permission: direct publish or staged publish`)
  }

  const args = ['trust', source.type, packageName]
  if (source.type === 'github') {
    args.push('--file', basename(source.file), '--repo', source.repository)
  }
  else if (source.type === 'gitlab') {
    args.push('--file', basename(source.file), '--project', source.project)
  }
  else {
    args.push('--org-id', source.orgId, '--project-id', source.projectId, '--pipeline-definition-id', source.pipelineDefinitionId, '--vcs-origin', source.vcsOrigin)
    for (const contextId of source.contextIds ?? []) {
      args.push('--context-id', contextId)
    }
  }
  if (source.type !== 'circleci' && source.environment) {
    args.push('--env', source.environment)
  }
  if (allowPublish) {
    args.push('--allow-publish')
  }
  if (allowStagePublish) {
    args.push('--allow-stage-publish')
  }
  args.push('--yes', '--json')
  if (dryRun) {
    args.push('--dry-run')
  }
  return args
}

/**
 * Create a trusted publisher configuration for a package (`npm trust
 * github|gitlab|circleci`), with the npm login and 2FA of a maintainer. A new
 * configuration must complete a first successful publish within 2 days, or
 * npm removes it.
 *
 * @param options - Package, source, permissions, code and runner.
 * @param options.cwd - Root of the project.
 * @param options.packageName - Package, which must exist on npm.
 * @param options.source - The workflow trusted.
 * @param options.allowPublish - Allow a direct publish (`--allow-publish`).
 * @param options.allowStagePublish - Allow a staged publish (`--allow-stage-publish`).
 * @param options.dryRun - Ask npm what it would do (`--dry-run`).
 * @param options.otp - The 2FA code.
 * @param options.runner - Runs npm.
 * @param options.env - Environment to check.
 * @param options.timeoutMs - Timeout of the npm call.
 * @param options.logger - Receives debug messages.
 * @returns The configurations npm printed.
 * @throws `InteractiveAuthRequiredError`, the OTP error of npm when it needs a code, `TrustedPublisherError` otherwise.
 * @example
 * ```ts
 * await createTrustedPublisher({
 *   cwd: '/repo',
 *   packageName: '@scope/core',
 *   source: { type: 'github', file: 'release.yml', repository: 'acme/repo' },
 *   allowPublish: true,
 *   allowStagePublish: false,
 *   otp: '123456',
 * })
 * ```
 */
export async function createTrustedPublisher(options: TrustCallOptions & {
  source: TrustedPublisherSource
  allowPublish: boolean
  allowStagePublish: boolean
  dryRun?: boolean
}): Promise<TrustedPublisher[]> {
  const stdout = await runTrust(options, getTrustArgs(options))
  return parseJsonStream(stdout)
    .filter((value): value is Record<string, unknown> => typeof value === 'object' && value !== null)
    .map(toPublisher)
}

/**
 * Remove a trusted publisher configuration (`npm trust revoke <pkg> --id`)
 *
 * @param options - Package, id, code and runner.
 * @param options.cwd - Root of the project.
 * @param options.packageName - Package.
 * @param options.id - Id of the configuration (from `listTrustedPublishers`).
 * @param options.otp - The 2FA code.
 * @param options.runner - Runs npm.
 * @param options.env - Environment to check.
 * @param options.timeoutMs - Timeout of the npm call.
 * @param options.logger - Receives debug messages.
 * @returns Resolves once npm removed it.
 * @throws `InteractiveAuthRequiredError`, the OTP error of npm when it needs a code, `TrustedPublisherError` otherwise.
 * @example
 * ```ts
 * await revokeTrustedPublisher({ cwd: '/repo', packageName: '@scope/core', id: 'a1b2', otp: '123456' })
 * ```
 */
export async function revokeTrustedPublisher(options: TrustCallOptions & { id: string }): Promise<void> {
  await runTrust(options, [
    'trust',
    'revoke',
    options.packageName,
    '--id',
    options.id,
    // The web 2FA links of npm are only given in its JSON error
    '--json',
  ])
}

function readEnvironment(job: unknown): string | undefined {
  if (typeof job !== 'object' || job === null) {
    return undefined
  }
  const environment = (job as { environment?: unknown }).environment
  if (typeof environment === 'string') {
    return environment
  }
  if (typeof environment === 'object' && environment !== null && typeof (environment as { name?: unknown }).name === 'string') {
    return (environment as { name: string }).name
  }
  return undefined
}

const RELEASES_WITH_RELIZY = /relizy(?:@\S+)?\s+(?:release|publish)\b|uses"?:\s*"?[^\s"]*\/relizy|relizy\/gitlab-component/

/** Runs relizy for real somewhere: a workflow that only runs `relizy release --dry-run` publishes nothing */
function publishesWithRelizy(code: string): boolean {
  if (!RELEASES_WITH_RELIZY.test(code)) {
    return false
  }
  const commands = code.match(/relizy(?:@\S+)?\s+(?:release|publish)\b.*/g) ?? []
  return commands.length === 0 || commands.some(command => !command.includes('--dry-run'))
}

const RESERVED_GITLAB_KEYS = new Set([
  'stages',
  'variables',
  'include',
  'default',
  'workflow',
  'image',
  'services',
  'cache',
  'before_script',
  'after_script',
  'spec',
])

function readJobs(provider: 'github' | 'gitlab', content: string): { name: string, environment?: string }[] {
  let parsed: unknown
  try {
    // The spec header of a component file is separated by `---`: only the jobs part is read
    parsed = parseYAML(content.split(/^---$/m).at(-1) ?? content)
  }
  catch {
    return []
  }
  if (typeof parsed !== 'object' || parsed === null) {
    return []
  }

  const entries = provider === 'github'
    ? Object.entries((parsed as { jobs?: Record<string, unknown> }).jobs ?? {})
    : Object.entries(parsed as Record<string, unknown>).filter(([name]) => !RESERVED_GITLAB_KEYS.has(name) && !name.startsWith('.'))

  const jobs = entries.map(([name, job]) => ({
    name,
    job,
    releases: RELEASES_WITH_RELIZY.test(JSON.stringify(job)),
  }))
  const releasing = jobs.filter(job => job.releases)

  return (releasing.length > 0
    ? releasing
    : jobs).map(({ name, job }) => {
    const environment = readEnvironment(job)
    return environment
      ? { name, environment }
      : { name }
  })
}

/**
 * The CI workflows that release with relizy: the GitHub Actions workflows and
 * the GitLab CI file written by `relizy init`, those running `relizy release`
 * or `relizy publish` (or the relizy action or component), and the files
 * given. For each one: the file name npm matches (the calling workflow on
 * GitHub, `.gitlab-ci.yml` on GitLab), the repository of the git remote, and
 * the jobs that release with their environment.
 *
 * @param options - Project and files.
 * @param options.cwd - Root of the project.
 * @param options.files - Workflow files to read too (paths relative to `cwd`).
 * @param options.logger - Receives a warning when the remote is not recognized.
 * @returns The workflows found, GitHub ones first.
 * @example
 * ```ts
 * await readReleaseWorkflows({ cwd: '/repo' })
 * // [{ provider: 'github', file: 'release.yml', path: '.github/workflows/release.yml', repository: 'acme/repo', generated: true, jobs: [{ name: 'release' }] }]
 * ```
 */
export async function readReleaseWorkflows({ cwd, files = [], logger }: { cwd: string, files?: string[], logger?: CoreLogger }): Promise<ReleaseWorkflow[]> {
  const repo = await resolveRepoConfig(cwd, { logger })
  const workflows: ReleaseWorkflow[] = []

  for (const provider of ['github', 'gitlab'] as const) {
    for (const ciFile of findCiFiles(cwd, provider)) {
      const raw = readFileSync(join(cwd, ciFile.file), 'utf8')
      const given = files.some(file => file === ciFile.file || basename(file) === basename(ciFile.file))
      const generated = raw.startsWith(GENERATED_HEADER) && !raw.includes('guide/merge-preview')
      if (!given && !generated && !publishesWithRelizy(ciFile.code)) {
        continue
      }
      // GitLab matches the CI config file of the project, not an included one
      if (provider === 'gitlab' && ciFile.file !== '.gitlab-ci.yml' && !given) {
        continue
      }

      workflows.push({
        provider,
        file: basename(ciFile.file),
        path: ciFile.file,
        repository: repo?.repo,
        generated,
        jobs: readJobs(provider, ciFile.code),
      })
    }
  }

  return workflows
}
