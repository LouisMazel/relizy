import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { logger } from '@maz-ui/node'
import { findOutdatedRules, formatAgentsChanges, getDefaultAgentTargets, mcpInit, readOwnAgentDocs, RELIZY_AGENTS_TOOL, setupRelizyAgents } from '../agents'
import { readOwnVersion } from '../version'
import { cleanTempDirs, createTempDir, getBundleDir } from './helpers'

let cwd: string

beforeEach(() => {
  cwd = createTempDir()
})

afterAll(() => {
  cleanTempDirs()
})

function read(file: string): string {
  return readFileSync(join(cwd, file), 'utf8')
}

describe('Given setupRelizyAgents', () => {
  describe('When the project uses Claude Code', () => {
    it('Then it writes the relizy rule and registers relizy mcp', () => {
      writeFileSync(join(cwd, 'CLAUDE.md'), '# project')

      const result = setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })

      expect(result.targets).toEqual(['claude'])
      expect(read('.claude/rules/relizy.md')).toContain(`<!-- Managed by relizy ${readOwnVersion()}`)
      expect(read('.claude/rules/relizy.md')).toContain('generated by `relizy mcp init`')
      expect(read('.claude/rules/relizy.md')).toContain(`> relizy ${readOwnVersion()} is installed: these rules and the docs in \`node_modules/relizy/agent-docs\` match this version.`)
      expect(JSON.parse(read('.mcp.json'))).toEqual({
        mcpServers: {
          relizy: {
            type: 'stdio',
            command: 'npx',
            args: ['-y', `relizy@${readOwnVersion()}`, 'mcp'],
          },
        },
      })
    })
  })

  describe('When the project installs relizy with pnpm', () => {
    it('Then the agents start the installed relizy', () => {
      writeFileSync(join(cwd, 'package.json'), JSON.stringify({
        packageManager: 'pnpm@10.0.0',
        devDependencies: { relizy: '^1.0.0' },
      }))

      const result = setupRelizyAgents({
        cwd,
        targets: ['cursor'],
        docsDir: getBundleDir(),
      })

      expect(result.localMcpServer).toBe(true)
      expect(JSON.parse(read('.cursor/mcp.json'))).toEqual({
        mcpServers: {
          relizy: {
            command: 'pnpm',
            args: ['exec', 'relizy', 'mcp'],
          },
        },
      })
    })
  })

  describe('When the project has no agent', () => {
    it('Then Claude Code and AGENTS.md are configured', () => {
      expect(getDefaultAgentTargets(cwd)).toEqual(['claude', 'agents-md'])

      setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })

      expect(read('AGENTS.md')).toContain('<!-- BEGIN:relizy -->')
      expect(read('AGENTS.md')).toContain('## relizy')
    })
  })

  describe('When the targets are invalid', () => {
    it('Then it lists the available ones', () => {
      expect(() => setupRelizyAgents({
        cwd,
        targets: ['claude', 'zed' as never],
      })).toThrow('Unknown agent target(s): zed. Available: claude, agents-md, cursor, vscode.')
    })
  })

  describe('When the setup is removed', () => {
    it('Then the files of relizy are removed', () => {
      setupRelizyAgents({
        cwd,
        docsDir: getBundleDir(),
      })
      setupRelizyAgents({ cwd, remove: true })

      expect(existsSync(join(cwd, 'AGENTS.md'))).toBe(false)
      expect(existsSync(join(cwd, '.mcp.json'))).toBe(false)
    })
  })
})

describe('Given readOwnAgentDocs', () => {
  describe('When the bundle has no rules', () => {
    it('Then it explains how to get them', () => {
      expect(() => readOwnAgentDocs(createTempDir())).toThrow('The rules of relizy for the agents are missing')
    })
  })

  describe('When the bundle has the rules', () => {
    it('Then they are read with the version of relizy', () => {
      expect(readOwnAgentDocs(getBundleDir())).toEqual(expect.objectContaining({
        version: readOwnVersion(),
        claudeRule: expect.stringMatching(/^# relizy/),
      }))
    })
  })
})

describe('Given findOutdatedRules', () => {
  describe('When the rules were generated by an older relizy', () => {
    it('Then they are reported, the up-to-date ones are not', () => {
      setupRelizyAgents({
        cwd,
        targets: ['agents-md'],
        docsDir: getBundleDir(),
      })
      mkdirSync(join(cwd, '.claude/rules'), { recursive: true })
      writeFileSync(join(cwd, '.claude/rules/relizy.md'), '<!-- Managed by relizy 0.1.0 (sha256:abc): x -->\n\n# relizy')

      expect(findOutdatedRules(cwd)).toEqual([
        { file: '.claude/rules/relizy.md', version: '0.1.0' },
      ])
      expect(findOutdatedRules(cwd, '0.0.1')).toEqual([])
    })
  })
})

describe('Given mcpInit', () => {
  describe('When it runs in dry run', () => {
    it('Then it prints the changes and the hints without writing', () => {
      vi.mocked(logger.log).mockClear()
      vi.mocked(logger.info).mockClear()

      const result = mcpInit({
        cwd,
        dryRun: true,
        docsDir: getBundleDir(),
      })

      // Without CLAUDE.md, Claude Code reads AGENTS.md: no Claude rule
      expect(result.changes.map(change => [change.file, change.action])).toEqual([
        ['AGENTS.md', 'create'],
        ['.mcp.json', 'create'],
      ])
      expect(existsSync(join(cwd, '.mcp.json'))).toBe(false)
      expect(logger.info).toHaveBeenCalledWith(expect.stringContaining('agents setup (claude, agents-md) - dry run'))
      expect(logger.log).toHaveBeenCalledWith('  would create  AGENTS.md')
      expect(logger.info).toHaveBeenCalledWith(expect.stringContaining('add relizy to the devDependencies'))
      expect(logger.info).toHaveBeenCalledWith(expect.stringContaining('Codex and Windsurf read AGENTS.md'))
    })
  })

  describe('When it removes the setup or only registers the server', () => {
    it('Then the hints are not printed', () => {
      vi.mocked(logger.info).mockClear()

      mcpInit({ cwd, remove: true })
      mcpInit({
        cwd,
        rules: false,
        mcp: false,
        targets: ['claude'],
      })

      expect(logger.info).not.toHaveBeenCalledWith(expect.stringContaining('devDependencies'))
      expect(logger.info).not.toHaveBeenCalledWith(expect.stringContaining('Codex'))
    })
  })
})

describe('Given formatAgentsChanges', () => {
  describe('When changes are printed', () => {
    it('Then each action has its label', () => {
      expect(formatAgentsChanges([
        { file: 'a', action: 'create' },
        { file: 'b', action: 'update' },
        { file: 'c', action: 'remove' },
        { file: 'd', action: 'unchanged' },
        { file: 'e', action: 'skip', reason: 'edited' },
      ], false)).toEqual([
        'created       a',
        'updated       b',
        'removed       c',
        'up to date    d',
        'skipped       e (edited)',
      ])
      expect(formatAgentsChanges([
        { file: 'a', action: 'update' },
      ], true)).toEqual(['would update  a'])
    })
  })
})

describe('Given RELIZY_AGENTS_TOOL', () => {
  describe('When it is read', () => {
    it('Then the agents run relizy mcp', () => {
      expect(RELIZY_AGENTS_TOOL).toEqual(expect.objectContaining({
        name: 'relizy',
        mcpPackage: 'relizy',
        mcpBin: 'relizy',
        mcpArgs: ['mcp'],
      }))
    })
  })
})
