import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createContext } from '../context'
import { startStdioServer } from '../server'
import { getConfigOption, stringifyConfigValue } from '../tools/get-config-option'
import { getDoc } from '../tools/get-doc'
import { getProject } from '../tools/get-project'
import { lintCommit } from '../tools/lint-commit'
import { MAX_CHANGELOGS_CHARS, previewChangelog } from '../tools/preview-changelog'
import { previewRelease } from '../tools/preview-release'
import { searchDocs } from '../tools/search-docs'
import { readOwnVersion } from '../version'
import { cleanTempDirs, createRepository, createTempDir, createTestContext, getBundleDir } from './helpers'

vi.mock('@maz-ui/node', importActual => importActual())

const transports = vi.hoisted(() => ({ created: 0 }))

vi.mock('@modelcontextprotocol/sdk/server/stdio.js', () => ({
  StdioServerTransport: class {
    start = vi.fn(() => Promise.resolve())
    close = vi.fn(() => Promise.resolve())
    send = vi.fn(() => Promise.resolve())

    constructor() {
      transports.created++
    }
  },
}))

afterAll(() => {
  cleanTempDirs()
})

function createApp(config: string) {
  const repository = createRepository()

  repository.writeJson('.', { name: 'app', version: '1.0.0' })
  repository.write('relizy.config.mjs', `export default { logLevel: 'silent', ${config} }\n`)
  repository.commit('chore: init')
  repository.git('tag', '-a', 'v1.0.0', '-m', 'v1.0.0')

  return repository
}

describe('Given startStdioServer', () => {
  describe('When it starts', () => {
    it('Then it connects the server to a stdio transport', async () => {
      // eslint-disable-next-line no-console -- restored after the test
      const original = { log: console.log, info: console.info, debug: console.debug }
      const server = await startStdioServer({ cwd: createTempDir(), docsDir: getBundleDir() })

      expect(transports.created).toBe(1)
      expect(server.isConnected()).toBe(true)
      await server.close()
      Object.assign(console, original)
    })
  })
})

describe('Given createContext', () => {
  describe('When no knowledge is given', () => {
    it('Then the bundle of docsDir is loaded on first use', () => {
      const context = createContext({ docsDir: getBundleDir() })

      expect(context.knowledge.directory).toBe(getBundleDir())
      expect(context.version).toBe(readOwnVersion())
    })
  })
})

describe('Given get_project on a folder without git nor package', () => {
  describe('When it is read', () => {
    it('Then it reports the defaults and no package', async () => {
      const text = await getProject(createTestContext(createTempDir()), {})

      expect(text).toContain('no relizy config file, the defaults apply')
      expect(text).toContain('branch `unknown`, last tag `none`')
      expect(text).toContain('No package.')
    })
  })
})

describe('Given get_project with relizy rules in the project', () => {
  describe('When the rules were generated by an older relizy', () => {
    it('Then it asks to run relizy mcp init, and says nothing once up to date', async () => {
      const repository = createApp('')

      repository.write('.claude/rules/relizy.md', '<!-- Managed by relizy 0.1.0 (sha256:abc): x -->\n\n# relizy\n')

      expect(await getProject(createTestContext(repository.cwd), {})).toContain('`.claude/rules/relizy.md` holds the rules of relizy 0.1.0: ask the user to run `relizy mcp init`')

      repository.write('.claude/rules/relizy.md', `<!-- Managed by relizy ${readOwnVersion()} (sha256:abc): x -->\n\n# relizy\n`)

      const text = await getProject(createTestContext(repository.cwd), {})

      expect(text).not.toContain('## Agents')
      expect(text).not.toContain('have no relizy rules')
    })
  })
})

describe('Given preview_release with every step of the release turned off', () => {
  describe('When it is previewed with force and fetchTags', () => {
    it('Then it reports no tag, the forced bump, and continues with the local tags', async () => {
      const repository = createApp(`release: { gitTag: false, publish: false, social: false, prComment: false, providerRelease: false, push: false }`)
      repository.git('remote', 'add', 'origin', join(repository.cwd, 'missing-remote'))

      const text = await previewRelease(createTestContext(repository.cwd), { force: true, type: 'patch', fetchTags: true })

      expect(text).toContain('1.0.0 → 1.0.1')
      expect(text).toContain('**Tags:** none (`release.gitTag` is off)')
      expect(text).toContain('`relizy release` would then write the changelogs, commit.')
      expect(text).toContain('Continuing with local tags')
    })

    it('Then it lists the steps of the release in their order, publishing before the release commit', async () => {
      const repository = createApp(`release: { prComment: false }`)

      const text = await previewRelease(createTestContext(repository.cwd), { force: true, type: 'patch' })

      expect(text).toContain('`relizy release` would then write the changelogs, publish to npm, commit, tag, push, create the GitHub/GitLab releases, post on the social networks.')
    })

    it('Then it leaves out the tags and the push without the release commit', async () => {
      const repository = createApp(`release: { commit: false, social: false, prComment: false, providerRelease: false }`)

      const text = await previewRelease(createTestContext(repository.cwd), { force: true, type: 'patch' })

      expect(text).toContain('`relizy release` would then write the changelogs, publish to npm.')
    })
  })

  describe('When a package of an independent monorepo is forced', () => {
    it('Then its bump is explained by the force', async () => {
      const repository = createRepository()
      repository.writeJson('.', { name: 'mono', version: '0.0.0', private: true })
      repository.writeJson('packages/a', { name: 'a', version: '1.0.0' })
      repository.write('relizy.config.mjs', `export default { logLevel: 'silent', monorepo: { versionMode: 'independent', packages: ['packages/*'] } }\n`)
      repository.commit('chore: init')
      repository.git('tag', '-a', 'a@1.0.0', '-m', 'a@1.0.0')

      const text = await previewRelease(createTestContext(repository.cwd), { force: true, type: 'patch' })

      expect(text).toContain('| `a` (`packages/a`) | 1.0.0 → 1.0.1 | forced (`force`) |')
    })
  })
})

describe('Given preview_changelog with huge changelogs', () => {
  describe('When they exceed the size of a result', () => {
    it('Then they are cut and the agent is told to request them one by one', async () => {
      const repository = createApp('')
      repository.commit(`feat: add a big feature\n\n${'Long line of explanation.\n'.repeat(MAX_CHANGELOGS_CHARS / 20)}`, { 'feature.js': 'export {}' })

      const text = await previewChangelog(createTestContext(repository.cwd), {})

      expect(text).toContain('The other changelogs are cut (1 in total): request them one by one with `package`.')
      expect(text.length).toBeLessThan(MAX_CHANGELOGS_CHARS)
    })
  })
})

describe('Given lint_commit with an unknown rule in the config', () => {
  describe('When a message is linted', () => {
    it('Then the warning of relizy is returned in the notes', async () => {
      const repository = createApp(`commitlint: { rules: { 'no-such-rule': 'error' } }`)

      const text = await lintCommit(createTestContext(repository.cwd), { message: 'feat: add a', files: [] })

      expect(text).toContain('## Notes')
      expect(text).toContain('no-such-rule')
    })
  })
})

describe('Given lint_commit on an ignored message', () => {
  describe('When a merge commit is linted', () => {
    it('Then it is reported as ignored', async () => {
      const repository = createApp('')

      expect(await lintCommit(createTestContext(repository.cwd), { message: 'Merge branch \'develop\' into main' })).toContain(': ignored')
    })
  })
})

describe('Given the knowledge tools on edge cases', () => {
  const context = createTestContext()

  describe('When a query only loosely matches the docs', () => {
    it('Then the results are flagged as weak matches', () => {
      expect(searchDocs(context, { query: 'docker image' })).toContain('These results are weak matches')
    })
  })

  describe('When a doc is not found and nothing is close', () => {
    it('Then the error only gives the expected ids', () => {
      expect(() => getDoc(context, { id: 'zzqxw' })).toThrow(/^No relizy doc matches "zzqxw"\.\n\nPass an id/)
    })
  })

  describe('When an option is not found but its last key exists', () => {
    it('Then the error suggests the options with this key', () => {
      expect(() => getConfigOption(context, { path: 'groups' })).toThrow('- `monorepo.groups` (`VersionGroup[]`)')
    })
  })

  describe('When an option is not found and nothing is close', () => {
    it('Then the error only gives the way to list the options', () => {
      expect(() => getConfigOption(context, { path: 'zzqxw' })).toThrow(/^relizy \S+ has no config option "zzqxw"\.\n\nList the options/)
    })
  })

  describe('When a config value holds functions and regular expressions', () => {
    it('Then they are serialized as text', () => {
      expect(stringifyConfigValue({ run: () => {}, match: /^v\d/, value: 1 })).toBe('{"run":"[function]","match":"/^v\\\\d/","value":1}')
      expect(stringifyConfigValue(undefined)).toBeUndefined()
    })
  })
})

describe('Given a docs bundle where an option has a long default', () => {
  describe('When the option is read', () => {
    it('Then the runtime default is left out', () => {
      const directory = createTempDir()
      const { manifest } = createTestContext().knowledge

      mkdirSync(directory, { recursive: true })
      writeFileSync(join(directory, 'manifest.json'), JSON.stringify({ ...manifest, config: [{ path: 'types', type: 'Record<string, object>', description: 'Types', docId: 'config/changelog' }] }))

      expect(getConfigOption(createContext({ docsDir: directory }), { path: 'types' })).not.toContain('**Default:**')
    })
  })
})
